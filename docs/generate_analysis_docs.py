from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.utils import get_column_letter

wb = Workbook()
HDR = PatternFill('solid', fgColor='4F46E5'); SUB = PatternFill('solid', fgColor='EEF2FF')
thin = Side(style='thin', color='CBD5E1'); B = Border(left=thin, right=thin, top=thin, bottom=thin)
WRAP = Alignment(wrap_text=True, vertical='top')

def sheet(title, doc_title, headers, rows, widths, first=False):
    ws = wb.active if first else wb.create_sheet()
    ws.title = title
    ws['A1'] = doc_title; ws['A1'].font = Font(size=15, bold=True, color='1E1B4B')
    ws['A2'] = '프로젝트: FitLife (운동·식단·수면 통합 건강관리)  |  작성일: 2026-10-13  |  버전: 1.0'
    ws['A2'].font = Font(size=9, color='64748B')
    r0 = 4
    for i, h in enumerate(headers, 1):
        c = ws.cell(r0, i, h); c.fill = HDR; c.font = Font(bold=True, color='FFFFFF'); c.alignment = Alignment(horizontal='center', vertical='center', wrap_text=True); c.border = B
    for ri, row in enumerate(rows, r0 + 1):
        for ci, v in enumerate(row, 1):
            c = ws.cell(ri, ci, v); c.alignment = WRAP; c.border = B
            if ri % 2 == 0: c.fill = SUB
    for i, w in enumerate(widths, 1): ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = ws.cell(r0 + 1, 1)
    ws.auto_filter.ref = f"A{r0}:{get_column_letter(len(headers))}{r0 + len(rows)}"
    return ws

